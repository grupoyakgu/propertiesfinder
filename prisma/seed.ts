async function main() {
  console.log(`Seeding ${RAW_PLOTS.length} plots...`);

  for (const p of RAW_PLOTS) {
    const slug = slugify(p.title, p.referenciaCatastral);
    const pricePerSqm = Math.round((p.purchasePrice / p.plotSize) * 100) / 100;
    const valorCatastral = Math.round(p.purchasePrice * 0.45);

    await prisma.plot.upsert({
      where: { referenciaCatastral: p.referenciaCatastral },
      update: {},
      create: {
        title: p.title,
        slug,
        referenciaCatastral: p.referenciaCatastral,
        address: p.address,
        municipality: p.municipality,
        province: p.province,
        autonomousCommunity: p.autonomousCommunity,
        postalCode: p.postalCode,
        latitude: p.latitude,
        longitude: p.longitude,
        description: p.description,
        plotSize: p.plotSize,
        builtArea: p.builtArea ?? 0,
        superficieGrafica: p.superficieGrafica ?? p.plotSize,
        constructionYear: p.constructionYear,
        landUse: p.landUse,
        cadastralUse: p.cadastralUse,
        buildingType: p.buildingType,
        numberOfFloors: p.numberOfFloors ?? 0,
        maxBuildableArea: p.maxBuildableArea,
        buildabilityRatio: p.buildabilityRatio,
        occupancyRatio: p.occupancyRatio,
        plotShape: p.plotShape,
        cornerPlot: p.cornerPlot ?? false,
        frontageWidth: p.frontageWidth,
        depth: p.depth,
        valorCatastral,
        planningStatus: p.planningStatus,
        developmentPotential: p.developmentPotential,
        allowedUses: p.allowedUses,
        maxHeight: p.maxHeight,
        restrictions: p.restrictions ?? [],
        zoning: p.zoning,
        purchasePrice: p.purchasePrice,
        pricePerSqm,
        estimatedConstructionCost: p.estimatedConstructionCost,
        expectedROI: p.expectedROI,
        expectedYield: p.expectedYield,
        developmentMargin: p.developmentMargin,
        topography: p.topography,
        doubleFrontage: p.doubleFrontage ?? false,
        existingBuilding: p.existingBuilding ?? false,
        demolitionRequired: p.demolitionRequired ?? false,
        vacantLand: p.vacantLand ?? false,
        boundary: rectangleAround(p.latitude, p.longitude, Math.sqrt(p.plotSize) / 2),
        nearbyAmenities: p.nearbyAmenities ?? [],
      },
    });
  }

  console.log("Seed complete.");
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
